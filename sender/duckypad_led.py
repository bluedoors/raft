#!/usr/bin/env python3
"""duckypad_led.py — set a single duckyPad key LED over HID (command 0x04).

Requires the CUSTOM firmware that implements HID_COMMAND_SET_LED_SINGLE
(stock OG-duckyPad firmware returns status 6 / UNKNOWN_CMD — see the plan).
Opening the HID config interface needs ROOT on macOS, so this is invoked via
NOPASSWD sudo from Claude Code hooks (plan §6-A). It opens/closes the device
per call (no persistent handle → dodges the macOS keypress-lock bug) and
NO-OPS SILENTLY (exit 0) whenever the pad is absent or busy.

Usage:
  duckypad_led.py [--host <cmux|orca>] <ordinal> <state>   # one key
  duckypad_led.py [--host <cmux|orca>] --board 1:working 2:done ...  # whole board
  duckypad_led.py --index <0-14> <R> <G> <B>    # light a raw physical LED (calibration)
  duckypad_led.py --all-off                     # clear all 15 LEDs

  state: working|needs|done|failed|idle|off

`--host` declares who is writing. The pad holds one active profile and each host's
profile sends different keystrokes, so a write is REFUSED when the loaded profile
belongs to the other host — otherwise the board would lie about a host you aren't
looking at. An unknown profile number is allowed (a hand-made profile must not
lock anyone out). `--index` and `--all-off` bypass the gate: they are deliberate
manual operations, not status.

Run as root, e.g.:
  sudo /usr/local/libexec/duckypad_led.py 2 working
"""
import sys
import json
import fcntl

VID, PID, CFG_USAGE, CFG_PAGE = 0x0483, 0xD11C, 0x3A, 0x0001
NEOPIXEL_COUNT = 15

# state -> RGB
STATE_COLOR = {
    "working": (255, 120, 0),    # amber: session active / thinking
    "needs":   (0, 90, 255),     # blue: BLOCKED — a permission / approval prompt
    "done":    (0, 200, 0),      # green: just finished, your turn (fades to off — see hook)
    "failed":  (255, 0, 0),      # red: turn ended in failure; stays lit until next state
    "idle":    (40, 0, 60),      # dim purple: finished + waiting a while (idle notification)
    "off":     (0, 0, 0),        # cleared
}

# Workspace ordinal (matches ⌘N) -> physical LED index 0-14.
# CALIBRATED 2026-07-17 for landscape, USB cable at top-left (portrait rotated
# 90deg CCW). Grid of LED indices in that orientation:
#     top:     2  5  8 11 14   <- workspace status row (WS1..WS5)
#     middle:  1  4  7 10 13
#     bottom:  0  3  6  9 12
# Only 5 keys in the top row, so workspaces 6+ get no status LED in this layout.
WS_LED_INDEX = {1: 2, 2: 5, 3: 8, 4: 11, 5: 14}

# Board ownership: the pad has ONE active profile and the cmux/Orca profiles send
# different keystrokes, so only the host whose profile is loaded may write LEDs —
# otherwise a board lies. The map is generated by duckypad_push_profile.py.
PROFILE_MAP_PATH = "/usr/local/libexec/duckypad_profiles.json"
PROFILE_HOST_DEFAULT = {1: "cmux", 2: "orca"}
LOCK_PATH = "/tmp/duckypad_led.lock"


def load_profile_host_map(path=None):
    """{profile_number: host}. Falls back to the built-in default."""
    try:
        with open(path or PROFILE_MAP_PATH) as f:
            return {int(k): str(v) for k, v in json.load(f).items()}
    except Exception:
        return dict(PROFILE_HOST_DEFAULT)


def host_owns_board(host, current_profile, profile_map):
    """May `host` write? Unknown or unreadable profiles are allowed on purpose:
    a user with a hand-made profile must not be locked out, and a single-host
    user never has a conflicting writer anyway."""
    if not host or current_profile is None:
        return True
    owner = profile_map.get(current_profile)
    return owner is None or owner == host


def parse_board(items):
    """["1:working", …] -> [(ordinal, state)], silently dropping nonsense."""
    out = []
    for item in items:
        ordinal, _, state = (item or "").partition(":")
        try:
            ordinal = int(ordinal)
        except ValueError:
            continue
        state = state.lower()
        if ordinal in WS_LED_INDEX and state in STATE_COLOR:
            out.append((ordinal, state))
    return out


def _query_current_profile(h):
    """HID 0x00 query-info → current profile number (response byte 11)."""
    buf = [0] * 64
    buf[0] = 0x05
    buf[2] = 0x00
    try:
        h.write(buf)
        resp = h.read(64, timeout_ms=200)
        return resp[11] if resp and len(resp) > 11 else None
    except Exception:
        return None


def _open_device():
    """Return an opened hid.device on the config interface, or None if absent."""
    try:
        import hid
    except Exception:
        return None
    try:
        path = None
        for d in hid.enumerate(VID, PID):
            if d.get("usage") == CFG_USAGE and d.get("usage_page") == CFG_PAGE:
                path = d["path"]
                break
        if path is None:
            return None
        h = hid.device()
        h.open_path(path)
        h.set_nonblocking(0)
        return h
    except Exception:
        return None


def _set_led(h, index, r, g, b):
    """Send one 0x04 Set-RGB-Single packet. Returns status byte or None."""
    buf = [0] * 64
    buf[0] = 0x05          # HID usage id (PC -> duckyPad)
    buf[2] = 0x04          # HID_COMMAND_SET_LED_SINGLE
    buf[3] = index & 0xFF
    buf[4], buf[5], buf[6] = r & 0xFF, g & 0xFF, b & 0xFF
    try:
        h.write(buf)
        resp = h.read(64, timeout_ms=200)
        return resp[2] if resp else None
    except Exception:
        return None


def main(argv):
    if len(argv) < 1:
        # No args: nothing to do. Silent success (hook-safe).
        return 0

    # Optional leading `--host <name>`: declares which host is asking, so the
    # ownership gate below can refuse writes aimed at another host's board.
    host = None
    if argv[0] == "--host":
        if len(argv) < 3:
            return 0
        host, argv = argv[1], argv[2:]

    # Calibration: light all 15 with distinct colors + print a legend, so the
    # index -> physical-key mapping can be read straight off the pad. (Step 3.)
    if argv[0] == "--calibrate":
        palette = [
            (255, 0, 0), (0, 255, 0), (0, 60, 255), (255, 120, 0), (255, 0, 200),
            (0, 255, 255), (255, 255, 255), (140, 70, 0), (150, 0, 255), (255, 60, 90),
            (60, 255, 0), (0, 130, 120), (80, 0, 0), (0, 80, 0), (0, 0, 90),
        ]
        names = ["RED", "GREEN", "BLUE", "ORANGE", "MAGENTA", "CYAN", "WHITE",
                 "BROWN", "PURPLE", "PINK", "LIME", "TEAL", "DIM-RED", "DIM-GREEN", "DIM-BLUE"]
        h = _open_device()
        if h is None:
            print("duckyPad absent — cannot calibrate")
            return 0
        try:
            for i in range(NEOPIXEL_COUNT):
                _set_led(h, i, *palette[i])
        finally:
            h.close()
        print("Lit all 15 keys. Legend (LED index -> color):")
        for i, n in enumerate(names):
            print(f"  index {i:2d} = {n}")
        print("\nHold the pad in your LANDSCAPE orientation and tell me the color grid,")
        print("reading left->right, top->bottom (note which edge the USB cable is on).")
        return 0

    # Parse into (list of (index, r, g, b)) actions.
    actions = []
    if argv[0] == "--all-off":
        actions = [(i, 0, 0, 0) for i in range(NEOPIXEL_COUNT)]
    elif argv[0] == "--board":
        # Whole board in one device open: unconditional and idempotent, which is
        # what makes it self-healing after an unplug, a sleep, or a missed event.
        actions = [(WS_LED_INDEX[o], *STATE_COLOR[s]) for o, s in parse_board(argv[1:])]
    elif argv[0] == "--index":
        if len(argv) != 5:
            return 0
        try:
            idx = int(argv[1]); r, g, b = int(argv[2]), int(argv[3]), int(argv[4])
        except ValueError:
            return 0
        if not 0 <= idx < NEOPIXEL_COUNT:
            return 0
        actions = [(idx, r, g, b)]
    else:
        if len(argv) < 2:
            return 0
        try:
            ordinal = int(argv[0])
        except ValueError:
            return 0
        state = argv[1].lower()
        if ordinal not in WS_LED_INDEX or state not in STATE_COLOR:
            return 0
        r, g, b = STATE_COLOR[state]
        actions = [(WS_LED_INDEX[ordinal], r, g, b)]

    # Serialise writers: two sessions finishing at once would otherwise interleave
    # two boards through one device.
    lock = None
    try:
        lock = open(LOCK_PATH, "w")
        fcntl.flock(lock, fcntl.LOCK_EX)
    except Exception:
        lock = None

    h = _open_device()
    if h is None:
        if lock:
            lock.close()
        return 0                      # pad absent → silent no-op
    try:
        if host is not None:
            current = _query_current_profile(h)
            profile_map = load_profile_host_map()
            if not host_owns_board(host, current, profile_map):
                # Say so. A silent refusal is indistinguishable from a successful
                # write at the call site, and "nothing lit" is also what every
                # real bug looks like — this line is the difference between
                # diagnosing in seconds and bisecting the whole chain.
                print(f"refusing {host} board write: pad profile {current} "
                      f"belongs to {profile_map.get(current)}", file=sys.stderr)
                return 0              # another host owns the board: write nothing
        for idx, r, g, b in actions:
            _set_led(h, idx, r, g, b)
    finally:
        try:
            h.close()
        except Exception:
            pass
        if lock:
            try:
                fcntl.flock(lock, fcntl.LOCK_UN)
            finally:
                lock.close()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
